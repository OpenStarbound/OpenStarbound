#!/bin/sh
# Rewrites assets/opensb/opensb/credits/contributors.json from the contributors of the GitHub repository, for the OpenStarbound
# page at the end of the credits (assets/opensb/cinematics/story/finale/finale.cinematic.patch.lua shows the list).
#
# It needs curl and jq. GITHUB_TOKEN is optional, but without one the API only allows 60 requests an hour per address.
# CREDITS_REPO picks another repository (default OpenStarbound/OpenStarbound, also in forks, so a fork's build credits the project).
#
# The names are the GitHub accounts of everyone with commits on the default branch (squashed pull requests count for the author
# of the pull request; the Co-authored-by trailers are not counted), in alphabetical order. Bots and the accounts listed in
# scripts/credits/excluded.txt are left out.
#
# This never fails a build: if anything goes wrong, or the answer looks wrong, the file in the repository is left as it is.
cd "$(dirname "$0")/../.." || exit 0

repo="${CREDITS_REPO:-OpenStarbound/OpenStarbound}"
out=assets/opensb/opensb/credits/contributors.json
excluded=scripts/credits/excluded.txt
# fewer names than this means the API did not give the whole list
minimum=10

skip() {
  echo "credits: $1, keeping $out" >&2
  rm -f "$work" "$work.json"
  exit 0
}

command -v curl >/dev/null 2>&1 || { echo "credits: curl is missing, keeping $out" >&2; exit 0; }
command -v jq >/dev/null 2>&1 || { echo "credits: jq is missing, keeping $out" >&2; exit 0; }
work="$(mktemp)" || exit 0

page=1
while :; do
  json="$(curl -fsS --retry 2 --max-time 30 \
    -H "Accept: application/vnd.github+json" \
    ${GITHUB_TOKEN:+-H "Authorization: Bearer $GITHUB_TOKEN"} \
    "https://api.github.com/repos/$repo/contributors?per_page=100&page=$page")" || skip "could not read the contributors of $repo"
  count="$(printf '%s' "$json" | jq 'length' 2>/dev/null)" || skip "the contributors of $repo were not a list"
  [ "$count" -gt 0 ] || break
  # bots have type "Bot" (and a login ending in [bot])
  printf '%s' "$json" | jq -r '.[] | select(.type == "User" and (.login | endswith("[bot]") | not)) | .login' >> "$work" || skip "could not read the names"
  [ "$count" -ge 100 ] || break
  page=$((page + 1))
done

# leave out the accounts in the exclusion list (one login per line, # starts a comment), then sort and drop repeats
if [ -f "$excluded" ]; then
  sed 's/#.*//; s/[[:space:]]//g; /^$/d' "$excluded" > "$work.excluded"
  grep -v -i -x -F -f "$work.excluded" "$work" > "$work.kept" || true
  mv "$work.kept" "$work"
  rm -f "$work.excluded"
fi
sort -f -u "$work" -o "$work"

total="$(wc -l < "$work" | tr -d ' ')"
[ "$total" -ge "$minimum" ] || skip "only $total names came back"

{
  echo "// The names shown on the OpenStarbound page at the end of the credits (see cinematics/story/finale/finale.cinematic.patch.lua)."
  echo "// Generated by scripts/credits/generate-contributors.sh from the contributors of the GitHub repository when a release is built."
  echo "// To be left out, add a GitHub login to scripts/credits/excluded.txt."
  jq -n --arg heading "OPENSTARBOUND" --rawfile names "$work" \
    '{heading: $heading, contributors: ($names | split("\n") | map(select(. != "")))}'
} > "$work.json" || skip "could not write the list"

mv "$work.json" "$out"
rm -f "$work"
echo "credits: wrote $total names to $out"
